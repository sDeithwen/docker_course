#!/bin/bash
# ============================================
# DOCKER RUN ШПАРГАЛКА
# ============================================

# ------------------------------------------
# БАЗОВЫЙ ЗАПУСК КОНТЕЙНЕРА
# ------------------------------------------

# image (обязательный параметр)
# docker run ИМЯ_ОБРАЗА:ТЕГ
docker run ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# container_name (имя контейнера)
# ------------------------------------------
# --name ИМЯ_КОНТЕЙНЕРА
docker run --name ИМЯ_КОНТЕЙНЕРА ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# ports (проброс портов)
# ------------------------------------------
# -p ХОСТ_ПОРТ:КОНТЕЙНЕР_ПОРТ
docker run -p ХОСТ_ПОРТ:КОНТЕЙНЕР_ПОРТ ИМЯ_ОБРАЗА:ТЕГ

# Несколько портов
docker run \
  -p ХОСТ_ПОРТ_1:КОНТЕЙНЕР_ПОРТ_1 \
  -p ХОСТ_ПОРТ_2:КОНТЕЙНЕР_ПОРТ_2 \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# volumes (bind mount - привязка к хосту)
# ------------------------------------------
# -v ПУТЬ_НА_ХОСТЕ:ПУТЬ_В_КОНТЕЙНЕРЕ
docker run -v ./ПУТЬ_НА_ХОСТЕ:ПУТЬ_В_КОНТЕЙНЕРЕ ИМЯ_ОБРАЗА:ТЕГ

# Абсолютный путь
docker run -v /АБСОЛЮТНЫЙ_ПУТЬ:ПУТЬ_В_КОНТЕЙНЕРЕ ИМЯ_ОБРАЗА:ТЕГ

# Несколько томов
docker run \
  -v ./ПУТЬ_1:ПУТЬ_В_КОНТЕЙНЕРЕ_1 \
  -v /АБСОЛЮТНЫЙ_ПУТЬ_2:ПУТЬ_В_КОНТЕЙНЕРЕ_2 \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# volumes (именованные тома)
# ------------------------------------------
# -v ИМЯ_ТОМА:ПУТЬ_В_КОНТЕЙНЕРЕ
docker run -v ИМЯ_ТОМА:ПУТЬ_В_КОНТЕЙНЕРЕ ИМЯ_ОБРАЗА:ТЕГ

# Создание тома перед использованием
docker volume create ИМЯ_ТОМА
docker run -v ИМЯ_ТОМА:ПУТЬ_В_КОНТЕЙНЕРЕ ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# networks (подключение к сетям)
# ------------------------------------------
# --network ИМЯ_СЕТИ
docker run --network ИМЯ_СЕТИ ИМЯ_ОБРАЗА:ТЕГ

# Создание сети перед использованием
docker network create ИМЯ_СЕТИ
docker run --network ИМЯ_СЕТИ ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# environment (переменные окружения)
# ------------------------------------------
# -e ПЕРЕМЕННАЯ=ЗНАЧЕНИЕ
docker run -e ПЕРЕМЕННАЯ=ЗНАЧЕНИЕ ИМЯ_ОБРАЗА:ТЕГ

# Из файла .env
docker run --env-file .env ИМЯ_ОБРАЗА:ТЕГ

# Несколько переменных
docker run \
  -e ПЕРЕМЕННАЯ_1=ЗНАЧЕНИЕ_1 \
  -e ПЕРЕМЕННАЯ_2=${ПЕРЕМЕННАЯ_ИЗ_ENV} \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# healthcheck (проверка здоровья)
# ------------------------------------------
# --health-cmd "КОМАНДА АРГУМЕНТ"
# --health-interval ИНТЕРВАЛ
# --health-timeout ТАЙМАУТ
# --health-retries ПОПЫТКИ
# --health-start-period ПЕРИОД_СТАРТА

docker run \
  --health-cmd "КОМАНДА АРГУМЕНТ" \
  --health-interval 5s \
  --health-timeout 3s \
  --health-retries 3 \
  --health-start-period 15s \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# КОМБИНИРОВАННЫЙ ПРИМЕР
# ------------------------------------------
# Полный пример с большинством параметров
docker run \
  --name ИМЯ_КОНТЕЙНЕРА \
  -p ХОСТ_ПОРТ:КОНТЕЙНЕР_ПОРТ \
  -v ИМЯ_ТОМА:ПУТЬ_В_КОНТЕЙНЕРЕ \
  -v ./ПУТЬ_НА_ХОСТЕ:ПУТЬ_В_КОНТЕЙНЕРЕ \
  --network ИМЯ_СЕТИ \
  -e ПЕРЕМЕННАЯ_1=${ПЕРЕМЕННАЯ_ИЗ_ENV_1} \
  -e ПЕРЕМЕННАЯ_2=${ПЕРЕМЕННАЯ_ИЗ_ENV_2} \
  --health-cmd "КОМАНДА АРГУМЕНТ" \
  --health-interval 5s \
  --health-timeout 3s \
  --health-retries 3 \
  --health-start-period 15s \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# ДОПОЛНИТЕЛЬНЫЕ ПОЛЕЗНЫЕ ПАРАМЕТРЫ
# ------------------------------------------

# Запуск в фоновом режиме (detach)
docker run -d ИМЯ_ОБРАЗА:ТЕГ

# Автоматическое удаление контейнера после остановки
docker run --rm ИМЯ_ОБРАЗА:ТЕГ

# Интерактивный режим с псевдо-TTY (для отладки)
docker run -it ИМЯ_ОБРАЗА:ТЕГ /bin/bash

# Рестарт политика
docker run --restart unless-stopped ИМЯ_ОБРАЗА:ТЕГ

# Установка рабочих директорий
docker run -w /ПУТЬ_В_КОНТЕЙНЕРЕ ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# УПРАВЛЕНИЕ СЕТЯМИ И ТОМАМИ
# ------------------------------------------

# Создание именованного тома
docker volume create ИМЯ_ТОМА

# Просмотр всех томов
docker volume ls

# Удаление тома
docker volume rm ИМЯ_ТОМА

# Создание сети
docker network create ИМЯ_СЕТИ

# Просмотр всех сетей
docker network ls

# Удаление сети
docker network rm ИМЯ_СЕТИ

# ------------------------------------------
# ПРОВЕРКА СОСТОЯНИЯ КОНТЕЙНЕРА
# ------------------------------------------

# Просмотр запущенных контейнеров
docker ps

# Просмотр всех контейнеров (включая остановленные)
docker ps -a

# Проверка healthcheck статуса
docker inspect --format='{{.State.Health.Status}}' ИМЯ_КОНТЕЙНЕРА

# Логи контейнера
docker logs ИМЯ_КОНТЕЙНЕРА

# Остановка контейнера
docker stop ИМЯ_КОНТЕЙНЕРА

# Запуск остановленного контейнера
docker start ИМЯ_КОНТЕЙНЕРА

# Удаление контейнера
docker rm ИМЯ_КОНТЕЙНЕРА

# ------------------------------------------
# RESTART POLICY (политика перезапуска)
# ------------------------------------------
# --restart ПОЛИТИКА
# no: никогда не перезапускать (по умолчанию)
# always: всегда перезапускать
# on-failure: перезапускать только при ошибке (код выхода != 0)
# unless-stopped: перезапускать, если контейнер не остановлен вручную

docker run --restart unless-stopped ИМЯ_ОБРАЗА:ТЕГ

# С максимальным количеством попыток (только для on-failure)
docker run --restart on-failure:5 ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# ОГРАНИЧЕНИЯ РЕСУРСОВ (RAM / CPU)
# ------------------------------------------
# --memory / -m: ограничение оперативной памяти
# --cpus: ограничение CPU (в ядрах, можно дробное)

# Ограничение RAM до 512 мегабайт
docker run -m 512M ИМЯ_ОБРАЗА:ТЕГ

# Ограничение CPU до 1.5 ядер (или 150% одного ядра)
docker run --cpus=1.5 ИМЯ_ОБРАЗА:ТЕГ

# Комбинированный пример с ресурсами и политикой перезапуска
docker run \
  --name ИМЯ_КОНТЕЙНЕРА \
  -m 512M \
  --cpus=0.5 \
  --restart unless-stopped \
  ИМЯ_ОБРАЗА:ТЕГ

# ------------------------------------------
# ПРОСМОТР ИСПОЛЬЗОВАНИЯ РЕСУРСОВ
# ------------------------------------------

# Статистика по запущенным контейнерам (RAM, CPU в реальном времени)
docker stats

# Статистика по конкретному контейнеру
docker stats ИМЯ_КОНТЕЙНЕРА

# Детальная информация о контейнере
docker inspect ИМЯ_КОНТЕЙНЕРА